"""Collect release dependency licenses and MPL sources. Author: jaswtao · Date: 2026-10-20."""
import argparse
import json
import os
import re
import shutil
import subprocess
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NOTICE = ROOT / "THIRD_PARTY_NOTICES.txt"
MANIFEST = ROOT / "THIRD_PARTY_LICENSES.json"


def command(*args):
    result = subprocess.run(args, cwd=ROOT, check=True, stdout=subprocess.PIPE,
                            encoding="utf-8", errors="strict")
    return json.loads(result.stdout)


def license_files(directory, explicit=None):
    candidates = []
    if explicit:
        candidates.append(directory / explicit)
    for item in directory.iterdir():
        if item.name.lower().startswith(("license", "licence", "copying", "notice", "copyright")):
            candidates.extend(item.rglob("*") if item.is_dir() else [item])
    result = []
    for path in sorted(set(candidates)):
        if path.is_file():
            result.append((path.relative_to(directory).as_posix(), path.read_text(encoding="utf-8", errors="replace").strip()))
    return result


def collect():
    metadata = command("cargo", "metadata", "--locked", "--format-version", "1",
                       "--filter-platform", "x86_64-pc-windows-msvc")
    packages = {p["id"]: p for p in metadata["packages"]}
    tree = subprocess.run(["cargo", "tree", "--locked", "--target", "x86_64-pc-windows-msvc",
                           "--package", "orbyte-desktop", "--edges", "normal,build",
                           "--prefix", "none", "--format", "{p}"], cwd=ROOT, check=True,
                          stdout=subprocess.PIPE, encoding="utf-8").stdout
    reachable = {match.groups() for line in tree.splitlines()
                 if (match := re.match(r"(\S+) v(\S+)", line))}
    records = {}
    for package in packages.values():
        if not package["source"] or (package["name"], package["version"]) not in reachable:
            continue
        directory = Path(package["manifest_path"]).parent
        source = f"https://crates.io/crates/{package['name']}/{package['version']}"
        records[("cargo", package["name"], package["version"])] = {
            "ecosystem": "cargo", "name": package["name"], "version": package["version"],
            "license": package["license"], "source": source, "directory": directory,
            "texts": license_files(directory, package.get("license_file")),
        }

    pnpm = shutil.which("pnpm.cmd" if os.name == "nt" else "pnpm")
    if not pnpm:
        raise RuntimeError("pnpm is required; run pnpm install --frozen-lockfile first.")
    trees = command(pnpm, "--filter", "orbyte-desktop", "list", "--prod", "--depth", "Infinity", "--json")

    def visit(dependencies):
        for name, dependency in dependencies.items():
            key = ("npm", name, dependency["version"])
            if key not in records:
                directory = Path(dependency["path"])
                package = json.loads((directory / "package.json").read_text(encoding="utf-8"))
                license_id = package.get("license")
                if isinstance(license_id, dict):
                    license_id = license_id.get("type")
                records[key] = {
                    "ecosystem": "npm", "name": name, "version": dependency["version"],
                    "license": license_id,
                    "source": f"https://www.npmjs.com/package/{name}/v/{dependency['version']}",
                    "directory": directory, "texts": license_files(directory),
                }
            visit(dependency.get("dependencies", {}))
            visit(dependency.get("optionalDependencies", {}))

    for tree in trees:
        visit(tree.get("dependencies", {}))
        visit(tree.get("optionalDependencies", {}))
    return [records[key] for key in sorted(records)]


def generate(check=False, mpl_sources=None):
    records = collect()
    supplements = json.loads((ROOT / "doc/third-party/overrides.json").read_text(encoding="utf-8"))
    for record in records:
        key = f"{record['ecosystem']}/{record['name']}@{record['version']}"
        if not record["texts"] and key in supplements:
            supplement = supplements[key]
            record["texts"] = [(Path(path).name, (ROOT / path).read_text(encoding="utf-8").strip()) for path in supplement["files"]]
            record["supplement"] = {k: supplement[k] for k in ("sources", "note")}
    for record in records:
        if not record["license"] or not record["texts"]:
            raise RuntimeError(f"Missing license metadata/text: {record['ecosystem']} {record['name']} {record['version']}")
    header = (
        "Orbyte third-party notices\n"
        "Generated by scripts/generate-licenses.py for Windows x64.\n"
        "Includes npm production dependencies and Rust normal/build dependencies.\n"
        "Original licenses apply to third-party code; Orbyte's MIT license does not replace them.\n"
        "MPL source: matching releases include third-party-mpl-sources.zip.\n"
        "See package URLs below for upstream sources and the exact versions.\n\n"
    )
    blocks = [header]
    public = []
    for record in records:
        public.append({k: record[k] for k in ("ecosystem", "name", "version", "license", "source")})
        if "supplement" in record:
            public[-1]["licenseSupplement"] = record["supplement"]
        blocks.append(f"{'=' * 72}\n{record['ecosystem']}: {record['name']} {record['version']}\n"
                      f"License: {record['license']}\nSource: {record['source']}\n")
        if "supplement" in record:
            blocks.append("License text provenance: " + json.dumps(record["supplement"], ensure_ascii=False) + "\n")
        for filename, text in record["texts"]:
            blocks.append(f"\n--- {filename} ---\n{text}\n")
    outputs = {NOTICE: "\n".join(blocks), MANIFEST: json.dumps(public, ensure_ascii=False, indent=2) + "\n"}
    for path, content in outputs.items():
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise RuntimeError(f"{path.name} is stale; run pnpm licenses and commit the output.")
        else:
            path.write_text(content, encoding="utf-8", newline="\n")
    if mpl_sources:
        destination = Path(mpl_sources).resolve()
        destination.parent.mkdir(parents=True, exist_ok=True)
        with zipfile.ZipFile(destination, "w", compression=zipfile.ZIP_DEFLATED, strict_timestamps=False) as archive:
            archive.writestr("README.txt", "Exact upstream MPL sources used by this Orbyte build.\n"
                             "License texts are retained in each package. No third-party source modifications are applied.\n")
            for record in records:
                if "MPL" not in record["license"]:
                    continue
                directory = record["directory"]
                prefix = f"{record['ecosystem']}/{record['name'].replace('/', '_')}-{record['version']}"
                for filename, text in record["texts"]:
                    archive.writestr(f"{prefix}/ORBYTE-NOTICES/{filename}", text)
                for source in sorted(directory.rglob("*")):
                    if source.is_file() and "node_modules" not in source.relative_to(directory).parts:
                        archive.write(source, f"{prefix}/{source.relative_to(directory).as_posix()}")
    print(f"Third-party notices {'verified' if check else 'generated'}: {len(records)} packages.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--mpl-sources", type=Path)
    args = parser.parse_args()
    generate(args.check, args.mpl_sources)
